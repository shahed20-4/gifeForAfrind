function displayAzkar() {
    azkarContainer.innerHTML = '';
    
    // خلط الأذكار عشوائياً (لكل مرة ترتيب مختلف)
    const shuffled = [...azkarList].sort(() => Math.random() - 0.5);
    
    shuffled.forEach((zekr, index) => {
        const zekrElement = document.createElement('div');
        zekrElement.className = 'azkar-item';
        zekrElement.innerHTML = `
            <div class="azkar-text">${zekr.text}</div>
            <div class="azkar-desc">${zekr.description}</div>
        `;
        
        // عند الضغط على أي ذكر يتم نسخه (لمسة إضافية)
        zekrElement.onclick = function() {
            navigator.clipboard.writeText(zekr.text);
            
            // إظهار رسالة صغيرة (بسيطة)
            const originalBg = this.style.background;
            this.style.background = 'linear-gradient(145deg, #D4AF37, #F0E68C)';
            setTimeout(() => {
                this.style.background = originalBg;
            }, 200);
        };
        
        azkarContainer.appendChild(zekrElement);
    });
}

