// حفظ فضفضة جديدة
saveFadfada.onclick = function() {
    const text = fadfadaText.value.trim();
    
    if (text === '') {
        alert('الماذا لم تكتب هل كلام صعبك عليك');
        return;
    }
    
    // إنشاء مذكرة جديدة
    const newEntry = {
        id: Date.now(),
        text: text,
        date: new Date().toLocaleString('ar-SA', {
            year: 'numeric',
            month: 'long',
            day: 'numeric',
            hour: '2-digit',
            minute: '2-digit'
        })
    };
    
    // حفظ في localStorage
    const entries = loadEntries();
    entries.push(newEntry);
    saveEntries(entries);
    
    // إغلاق النافذة
    fadfadaOverlay.classList.remove('show');
    
    // الرسالة الجميلة التي كتبتها أنت ❤️
    setTimeout(() => {
        alert('قد لا يكون أحد هنا ليسمع هذه المشاعر، لكنها تستحق أن تشارك حتى مع نفسك');
    }, 300);
};

