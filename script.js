// مفتاح التخزين في localStorage
const STORAGE_KEY = 'my_small_journal';

// تحميل المذكرات المحفوظة
function loadEntries() {
    const saved = localStorage.getItem(STORAGE_KEY);
    return saved ? JSON.parse(saved) : [];
}

// حفظ المذكرات
function saveEntries(entries) {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(entries));
}

// عرض المذكرات في الصفحة
function displayEntries() {
    const entries = loadEntries();
    
    if (entries.length === 0) {
        entriesContainer.innerHTML = `
            <div class="empty-journal">
                📭 لا توجد مذكرات بعد...<br>
                <small>اكتب أول فضفضة لك</small>
            </div>
        `;
        return;
    }
    
    // عرض المذكرات من الأحدث للأقدم
    entries.reverse().forEach(entry => {
        const entryCard = document.createElement('div');
        entryCard.className = 'entry-card';
        entryCard.innerHTML = `
            <div class="entry-date">${entry.date}</div>
            <div class="entry-text">${entry.text}</div>
            <button class="delete-entry" data-id="${entry.id}">🗑️</button>
        `;
        entriesContainer.appendChild(entryCard);
    });
    
    // إضافة حدث الحذف لكل بطاقة
    document.querySelectorAll('.delete-entry').forEach(btn => {
        btn.onclick = function(e) {
            e.stopPropagation();
            const id = this.dataset.id;
            deleteEntry(id);
        };
    });
}

// حذف مذكرة
function deleteEntry(id) {
    const entries = loadEntries();
    const updated = entries.filter(e => e.id != id);
    saveEntries(updated);
    
    // إعادة عرض المذكرات
    entriesContainer.innerHTML = '';
    displayEntries();
    
    // رسالة صغيرة (اختيارية)
    if (updated.length === 0) {
        // تم حذف الكل
    }
}

