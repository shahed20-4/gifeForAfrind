        let typingTimer = null;
        let currentTypingIndex = 0;
        let currentMessageText = '';
        let isTyping = false;

        function showMessage(messagesArray) {
            // إذا كان هناك تأثير كتابة قيد التشغيل، نوقفه
            if (typingTimer) {
                clearTimeout(typingTimer);
                typingTimer = null;
            }
            
            // التحقق من وجود رسائل في المصفوفة
            if (!messagesArray || messagesArray.length === 0) {
                messageArea.innerHTML = '<span class="empty-message">💝 لم تكتب رسالة لهذا الشعور بعد. عد لاحقاً وأضفها 💝</span>';
                return;
            }
            
            // اختيار رسالة عشوائية من المصفوفة
            const randomIndex = Math.floor(Math.random() * messagesArray.length);
            const fullMessage = messagesArray[randomIndex];
            
            if (!fullMessage) {
                messageArea.innerHTML = '<span class="empty-message">✨ رسالة فارغة ✨</span>';
                return;
            }
            
            // تجهيز تأثير الكتابة
            messageArea.innerHTML = ''; // تفريغ المنطقة
            currentMessageText = fullMessage;
            currentTypingIndex = 0;
            isTyping = true;
            
            // بدء تأثير الكتابة التدريجية
            function typeNextChar() {
                if (currentTypingIndex < currentMessageText.length) {
                    messageArea.innerHTML = currentMessageText.substring(0, currentTypingIndex + 1) + '<span class="typing-effect"></span>';
                    currentTypingIndex++;
                    
                    // سرعة الكتابة: عشوائية بين 50 و 150 مللي ثانية لإحساس طبيعي
                    const nextDelay = Math.random() * 100 + 50;
                    typingTimer = setTimeout(typeNextChar, nextDelay);
                } else {
                    // انتهت الكتابة
                    messageArea.innerHTML = currentMessageText;
                    isTyping = false;
                    typingTimer = null;
                }
            }
            
            typeNextChar();
        }


